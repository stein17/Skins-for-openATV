def build_progress_theme(style="blue"):
    values = PROGRESS_STYLES.get(style, PROGRESS_STYLES["blue"])
    return {
        "FullNightProgressUserDark": values["dark"],
        "FullNightProgressUserMiddle": values["middle"],
        "FullNightProgressUserLight": values["light"],
        "FullNightProgressUserSolid": values["solid"],
        "FullNightProgressUser": "FullNightProgressUserDark,FullNightProgressUserMiddle,FullNightProgressUserLight,horizontal",
    }


def progress_theme_bytes(style="blue"):
    root = ET.Element("skin")
    root.append(ET.Comment("Generated by PLi FullNight WQHD Setup - global progress colors"))
    group = ET.SubElement(root, "colors")
    for name, value in build_progress_theme(style).items():
        ET.SubElement(group, "color", name=name, value=value)
    if hasattr(ET, "indent"):
        ET.indent(root, space="\t")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)



def _argb_literal(value):
    """Convert '#AARRGGBB' to the integer literal used by MultiContentEntryProgress."""
    value = str(value).strip().lstrip("#")
    if len(value) == 6:
        value = "00" + value
    return "0x" + value.lower()


def _patch_multicontent_progress(style="blue"):
    """Make TemplatedMultiContent progress bars follow the global progress setting."""
    values = PROGRESS_STYLES.get(style, PROGRESS_STYLES["blue"])
    replacements = {
        "startColor": _argb_literal(values["dark"]),
        "midColor": _argb_literal(values["middle"]),
        "endColor": _argb_literal(values["light"]),
        "startColorSelected": _argb_literal(values["dark"]),
        "midColorSelected": _argb_literal(values["middle"]),
        "endColorSelected": _argb_literal(values["light"]),
    }
    for path in MULTICONTENT_PROGRESS_FILES:
        if not path.is_file():
            continue
        original = path.read_text(encoding="utf-8")
        lines = []
        changed = False
        for line in original.splitlines(True):
            if "MultiContentEntryProgress" in line:
                updated = line
                for key, value in replacements.items():
                    updated = re.sub(
                        r"\b%s=0x[0-9a-fA-F]+" % re.escape(key),
                        "%s=%s" % (key, value),
                        updated,
                    )
                if updated != line:
                    changed = True
                line = updated
            lines.append(line)
        if changed:
            temporary = path.with_suffix(path.suffix + ".tmp")
            temporary.write_text("".join(lines), encoding="utf-8")
            os.replace(str(temporary), str(path))



def write_progress_theme(style="blue", target=PROGRESS_THEME_PATH):
    target = Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    with temporary.open("wb") as handle:
        handle.write(progress_theme_bytes(style))
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(str(temporary), str(target))

    # Keep every non-gauge progress representation on the selected global style.
    _patch_multicontent_progress(style)

    # Legacy ServiceList only accepts one color via colorEventProgressbar,
    # but it can render a clipped pixmap. Keep that pixmap synchronized with
    # the selected global style so multi-color gradients work there too.
    service_style = style if style in PROGRESS_STYLES else "blue"
    service_source = SERVICE_EVENT_PROGRESS_DIR / ("service_event_%s.png" % service_style)
    if not service_source.is_file():
        service_source = SERVICE_EVENT_PROGRESS_DIR / "service_event_blue.png"
    if service_source.is_file():
        SERVICE_EVENT_PROGRESS_DIR.mkdir(parents=True, exist_ok=True)
        service_temporary = SERVICE_EVENT_PROGRESS_PATH.with_name(SERVICE_EVENT_PROGRESS_PATH.name + ".tmp")
        with service_source.open("rb") as source, service_temporary.open("wb") as destination:
            destination.write(source.read())
            destination.flush()
            os.fsync(destination.fileno())
        os.replace(str(service_temporary), str(SERVICE_EVENT_PROGRESS_PATH))

